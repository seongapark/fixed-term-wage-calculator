"""5-2 종별 -> 분류 매핑표 (고정값).

기획안 표는 "17종"이라 명시했으나 실제 나열은 16개뿐이고, 조퇴/지각/외출 x
(진단서미첨부/첨부) 조합 중 "조퇴(일반병가,진단서첨부)"가 빠져 있어 비대칭
(미첨부는 조퇴/지각/외출 3개 모두 있는데 첨부는 지각만 있음). 알 수 없는
종별은 classify()에서 예외를 던져 즉시 드러나므로, 안전하게 대칭 조합을
전부 채워 넣음(실제 e-사람 시스템에 해당 코드가 없으면 그냥 안 쓰일 뿐 무해).

기간제는 조퇴/외출/지각을 세부 종별이 아니라 "기타"로 등록하는 경우가 있다.
그래서 시간공제 대상 여부는 종별 문자열(접두사)이 아니라, 그 행에 실제
사용시간(시분)이 기재되어 있는지(=parser.py에서 시간을 파싱했는지)로
판정한다 - 판정 자체는 models.build_event()에서 이뤄지고, 이 모듈은
"시간 미기재(종일) 항목"일 때의 일수 가중치/판정 영향만 제공한다.
"""

CATEGORY_MAP = {
    "결근": "결근",
    "공가": "공가",
    "사망(본인 및 배우자의 조부모·외조부모)": "공가",
    "자녀돌봄휴가": "공가",
    "기타": "기타",
    "반일연가(오후)": "반일연가",
    "반일연가(오전)": "반일연가",
    "조퇴(일반병가,진단서미첨부)": "병가",
    "지각(일반병가,진단서미첨부)": "병가",
    "외출(일반병가,진단서미첨부)": "병가",
    "일반병가(진단서미첨부)": "병가",
    "연가": "연가",
    "외출(연가)": "연가",
    "조퇴(연가)": "연가",
    "일반병가(진단서첨부)": "병가",
    "지각(일반병가,진단서첨부)": "병가",
    "조퇴(일반병가,진단서첨부)": "병가",
    "외출(일반병가,진단서첨부)": "병가",
}

HALF_DAY_CATEGORIES = {"반일연가(오전)", "반일연가(오후)"}


def classify(raw_category: str) -> str:
    if raw_category not in CATEGORY_MAP:
        raise ValueError(f"알 수 없는 종별: {raw_category!r} (5-2 매핑표에 없음)")
    return CATEGORY_MAP[raw_category]


def full_day_weight(raw_category: str) -> float:
    """사용시간(시분) 미기재(종일) 항목의 일수 가중치."""
    if raw_category in HALF_DAY_CATEGORIES:
        return 0.5
    return 1.0


def full_day_breaks(raw_category: str) -> bool:
    """사용시간(시분) 미기재(종일) 항목이 5-1(주휴)/5-3(연가 만근) 판정을 깨는지.

    - 결근(전일) -> 깨짐
    - 병가(전일, 진단서 미첨부/첨부) -> 깨짐
    - 공가/기타/연가(전일)/반일연가 -> 무관(유지)
    """
    return classify(raw_category) in ("결근", "병가")
